import test from 'node:test';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { fixture, ownerCredentials, example } from './helpers.mjs';
import { normalizeSite } from '../lib/site-model.mjs';
import { migrateV1 } from '../lib/migrate-v1.mjs';

test('v2 editor: tabs, accordion, popups, pinned elements and repeaters', { timeout: 180000 }, async t => {
  const f = await fixture(); t.after(() => f.cleanup());
  const owner = await f.login();
  assert.equal((await f.save(owner, migrateV1(normalizeSite(example)))).status, 200);
  const browser = await chromium.launch(process.env.NIMBLE_BROWSER_CHANNEL ? { channel: process.env.NIMBLE_BROWSER_CHANNEL } : {});
  t.after(() => browser.close());
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.route('**/*', route => route.request().url().startsWith(f.base) || route.request().url().startsWith('about:') ? route.continue() : route.abort());
  const errors = [];
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(f.base + '/login.html');
  await page.locator('#email').fill(ownerCredentials.email); await page.locator('#password').fill(ownerCredentials.password);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.waitForURL('**/editor.html');
  const canvas = page.frameLocator('#canvasFrame');
  await canvas.locator('#intro').waitFor();
  const doc = () => page.evaluate(() => window.nimbleEditor.doc);
  const selected = () => page.evaluate(() => window.nimbleEditor.selected);
  const selectLayer = async id => { await page.locator('.rail-button[data-tool=layers]').click(); await page.locator('.layer-row[data-id="' + id + '"]').click(); };
  const add = async kind => { await page.locator('.rail-button[data-tool=add]').click(); await page.locator('#addPanel [data-add="' + kind + '"]').click(); return selected(); };
  const content = () => page.locator('#inspector [role=tab]', { hasText: 'Content' }).click();
  let tabs, accordion, popup;

  await t.test('tabs: panels switch on the canvas and are managed in the Content tab', async () => {
    await selectLayer('clip');
    tabs = await add('tabs');
    let state = await doc();
    assert.equal(state.nodes[tabs].type, 'tabs');
    assert.equal(state.nodes[tabs].children.length, 3);
    const [first, second] = state.nodes[tabs].children;
    assert.equal(await canvas.locator('#' + tabs + ' [role=tab]').count(), 3);
    assert.equal(await canvas.locator('#panel-' + second).isHidden(), true);
    await canvas.locator('#tab-' + second).click();
    assert.equal(await selected(), second, 'clicking a tab selects its panel');
    assert.equal(await canvas.locator('#panel-' + second).isVisible(), true);
    assert.equal(await canvas.locator('#panel-' + first).isHidden(), true);
    await selectLayer(tabs);
    await content();
    await page.locator('#inspector [data-panel-name="' + second + '"]').fill('Pricing');
    await page.locator('#inspector [data-panel-name="' + second + '"]').press('Tab');
    assert.equal(await canvas.locator('#tab-' + second).textContent(), 'Pricing');
    assert.equal(await canvas.locator('#panel-' + second).isVisible(), true, 'the shown panel survives re-rendering');
    await page.locator('#inspector [data-panel-add]').click();
    state = await doc();
    assert.equal(state.nodes[tabs].children.length, 4);
    assert.equal(state.nodes[state.nodes[tabs].children[3]].name, 'Tab 4');
    await page.locator('#inspector [data-panel="3"] [data-panel-remove]').click();
    await page.locator('#inspector [data-panel="2"] [data-panel-move="-1"]').click();
    state = await doc();
    assert.equal(state.nodes[tabs].children.length, 3);
    assert.equal(state.nodes[tabs].children[2], second);
    await page.locator('#inspector .field[data-key=tabStyle] select').selectOption('pills');
    assert.match(await canvas.locator('#' + tabs).getAttribute('class'), /is-pills/);
  });

  await t.test('accordion: titles open items on the canvas', async () => {
    await selectLayer('clip');
    accordion = await add('accordion');
    const state = await doc(), [, second] = state.nodes[accordion].children;
    const items = canvas.locator('#' + accordion + ' details');
    assert.equal(await items.count(), 3);
    assert.equal(await items.nth(0).evaluate(el => el.open), true, 'first item open');
    await items.nth(1).locator('summary').click();
    assert.equal(await selected(), second);
    assert.equal(await items.nth(1).evaluate(el => el.open), true);
    assert.equal(await items.nth(0).evaluate(el => el.open), false, 'one item at a time');
  });

  await t.test('popup: added as a page section, shown inline in the editor, linked from a button', async () => {
    popup = await add('popup');
    let state = await doc();
    assert.ok(state.pages[0].children.includes(popup));
    assert.equal(state.nodes[popup].props.popup, true);
    assert.equal(await canvas.locator('dialog.popup#popup-' + popup).isVisible(), true);
    await content();
    await page.locator('#inspector .field[data-key=popupOpen] select').selectOption('load');
    await page.locator('#inspector .field[data-key=popupDelay] input').fill('0');
    await page.locator('#inspector .field[data-key=popupDelay] input').press('Enter');
    await canvas.locator('#intro__button').click();
    await content();
    await page.locator('#inspector .field[data-key=link] [data-part=to]').selectOption('anchor');
    await page.locator('#inspector .field[data-key=link] [data-part=node]').selectOption(popup);
    state = await doc();
    assert.deepEqual(state.nodes.intro__button.props.link, { to: 'anchor', node: popup });
    assert.deepEqual(state.nodes[popup].props, { popup: true, popupOpen: 'load', popupDelay: 0, popupWidth: '520px' });
  });

  await t.test('pin an element and add a repeater', async () => {
    await canvas.locator('#intro__art').click();
    await page.locator('#inspector [role=tab]', { hasText: 'Layout' }).click();
    await page.locator('#inspector [data-lp-pin]').selectOption('top');
    await page.locator('#inspector [data-lp-len=pinOffset]').fill('24');
    await page.locator('#inspector [data-lp-len=pinOffset]').press('Enter');
    const place = (await doc()).nodes.intro__art.place.desktop;
    assert.equal(place.pin, 'top'); assert.equal(place.pinOffset, '24px');
    assert.equal(await canvas.locator('#intro__art').evaluate(el => getComputedStyle(el).position), 'sticky');
    await selectLayer('services');
    const repeater = await add('repeater');
    const state = await doc();
    assert.equal(state.nodes[repeater].children.length, 3);
    assert.equal(state.nodes[state.nodes[repeater].children[0]].children.length, 3);
  });

  await t.test('published tabs, accordion and popups work', async () => {
    await page.locator('#saveState').filter({ hasText: 'All changes saved' }).waitFor();
    const revision = (await f.request('/api/site', { auth: owner })).data.revision;
    assert.equal((await f.request('/api/publish', { method: 'POST', auth: owner, body: { revision } })).status, 200);
    const site = await context.newPage();
    site.on('pageerror', error => errors.push(error.message));
    await site.goto(f.base + '/');
    const dialog = site.locator('dialog#popup-' + popup);
    await site.waitForFunction(id => document.getElementById('popup-' + id).open, popup);
    await dialog.locator('.popup-close').click();
    assert.equal(await dialog.evaluate(el => el.open), false);
    const buttons = site.locator('#' + tabs + ' [role=tab]');
    await buttons.nth(2).click();
    const third = await buttons.nth(2).getAttribute('aria-controls');
    assert.equal(await site.locator('#' + third).isVisible(), true);
    await site.keyboard.press('ArrowLeft');
    assert.equal(await buttons.nth(1).getAttribute('aria-selected'), 'true');
    assert.equal(await site.evaluate(() => document.activeElement.getAttribute('role')), 'tab');
    const items = site.locator('#' + accordion + ' details');
    await items.nth(2).locator('summary').click();
    assert.equal(await items.nth(2).evaluate(el => el.open), true);
    await site.reload();
    await site.waitForTimeout(300);
    assert.equal(await dialog.evaluate(el => el.open), false, 'a load popup opens once per visit');
    await site.locator('#intro__button').click();
    assert.equal(await dialog.evaluate(el => el.open), true, 'links to the popup open it');
    await site.keyboard.press('Escape');
    assert.equal(await dialog.evaluate(el => el.open), false);
    await site.close();
  });
  assert.deepEqual(errors, []);
});

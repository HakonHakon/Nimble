import test from 'node:test';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { fixture, ownerCredentials, example } from './helpers.mjs';
import { normalizeSite } from '../lib/site-model.mjs';
import { migrateV1 } from '../lib/migrate-v1.mjs';

test('v2 editor: form builder with steps, choices and files; published form and inbox', { timeout: 180000 }, async t => {
  const f = await fixture(); t.after(() => f.cleanup());
  const owner = await f.login();
  assert.equal((await f.save(owner, migrateV1(normalizeSite(example)))).status, 200);
  const browser = await chromium.launch(process.env.NIMBLE_BROWSER_CHANNEL ? { channel: process.env.NIMBLE_BROWSER_CHANNEL } : {});
  t.after(() => browser.close());
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.route('**/*', route => route.request().url().startsWith(f.base) || route.request().url().startsWith('about:') ? route.continue() : route.abort());
  const errors = [];
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(f.base + '/login.html');
  await page.locator('#email').fill(ownerCredentials.email); await page.locator('#password').fill(ownerCredentials.password);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.waitForURL('**/editor.html');
  const canvas = page.frameLocator('#canvasFrame');
  await canvas.locator('#intro').waitFor();
  const doc = () => page.evaluate(() => window.nimbleEditor.doc);
  const fields = () => doc().then(state => state.nodes.inquiry__form.props.fields);
  const row = i => page.locator('#inspector [data-ff="' + i + '"]');

  await t.test('customise the contact form', async () => {
    await page.locator('.rail-button[data-tool=layers]').click();
    await page.locator('.layer-row[data-id="inquiry"]').click();
    await canvas.locator('#inquiry__form').click({ position: { x: 5, y: 5 } });
    assert.equal(await page.evaluate(() => window.nimbleEditor.selected), 'inquiry__form');
    await page.locator('#inspector [role=tab]', { hasText: 'Content' }).click();
    await page.locator('#inspector [data-ff-customize]').click();
    assert.deepEqual((await fields()).map(field => field.id), ['name', 'email', 'message']);
    await row(0).locator('[data-ff-width]').selectOption('half');
    await row(1).locator('[data-ff-width]').selectOption('half');
    await page.locator('#inspector [data-ff-add]').selectOption('step');
    await page.locator('#inspector [data-ff-add]').selectOption('radio');
    await row(4).locator('[data-ff-label]').fill('Budget');
    await row(4).locator('[data-ff-label]').press('Enter');
    await row(4).locator('[data-ff-options]').fill('Small\nMedium\nLarge');
    await row(4).locator('[data-ff-options]').blur();
    await row(4).locator('[data-ff-required]').check();
    await page.locator('#inspector [data-ff-add]').selectOption('file');
    await page.locator('#inspector [data-ff-add]').selectOption('checkbox');
    await row(6).locator('[data-ff-label]').fill('I accept the terms');
    await row(6).locator('[data-ff-label]').press('Enter');
    await row(6).locator('[data-ff-required]').check();
    await row(2).locator('[data-ff-move="1"]').click();
    let list = await fields();
    assert.deepEqual(list.map(field => field.type), ['text', 'email', 'step', 'textarea', 'radio', 'file', 'checkbox']);
    assert.deepEqual(list[4], { id: 'radio-1', type: 'radio', label: 'Budget', required: true, options: ['Small', 'Medium', 'Large'] });
    await page.locator('#inspector .field[data-key=success] textarea, #inspector .field[data-key=success] input').first().fill('Thanks, we will reply within a day.');
    await page.waitForFunction(() => window.nimbleEditor.doc.nodes.inquiry__form.props.success === 'Thanks, we will reply within a day.');
    assert.equal(await canvas.locator('#inquiry__form .form-step').count(), 2);
    assert.equal(await canvas.locator('#inquiry__form [data-form-next]').count(), 1);
  });

  await t.test('visitors fill in a two-step form with a file; the inbox lists every field', async () => {
    await page.locator('#saveState').filter({ hasText: 'All changes saved' }).waitFor();
    const revision = (await f.request('/api/site', { auth: owner })).data.revision;
    assert.equal((await f.request('/api/publish', { method: 'POST', auth: owner, body: { revision } })).status, 200);
    const site = await context.newPage();
    site.on('pageerror', error => errors.push(error.message));
    await site.goto(f.base + '/');
    const form = site.locator('#inquiry__form form');
    await form.locator('[data-form-next]').click();
    assert.equal(await form.locator('[data-step="1"]').isHidden(), true, 'required fields stop the first step');
    await form.locator('input[name=name]').fill('Grace Hopper');
    await form.locator('input[name=email]').fill('grace@example.com');
    await form.locator('[data-form-next]').click();
    assert.equal(await form.locator('[data-step="1"]').isVisible(), true);
    assert.equal(await form.locator('[data-form-current]').textContent(), '2');
    await form.locator('textarea[name=message]').fill('Please call me back.');
    await form.locator('input[name=radio-1][value=Medium]').check();
    await form.locator('input[type=file]').setInputFiles({ name: 'brief.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.7\nbrief') });
    await form.locator('input[name=checkbox-1]').check();
    await form.locator('button[type=submit]').click();
    await form.locator('[role=status]', { hasText: 'Thanks, we will reply within a day.' }).waitFor();
    await site.goto(f.base + '/control-panel.html');
    const card = site.locator('.message-card', { hasText: 'Grace Hopper' });
    await card.waitFor();
    assert.match(await card.locator('.message-fields').textContent(), /Budget\s*Medium/);
    const link = card.locator('a[download="brief.pdf"]');
    const download = site.waitForEvent('download');
    await link.click();
    assert.equal((await download).suggestedFilename(), 'brief.pdf');
    await site.close();
  });
  assert.deepEqual(errors, []);
});

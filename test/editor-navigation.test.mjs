import test from 'node:test';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { fixture, ownerCredentials, example } from './helpers.mjs';
import { normalizeSite } from '../lib/site-model.mjs';
import { migrateV1 } from '../lib/migrate-v1.mjs';

test('v2 editor: site menu with drop-downs, hamburger menu, header behaviour, social links and embeds', { timeout: 180000 }, async t => {
  const f = await fixture(); t.after(() => f.cleanup());
  const owner = await f.login();
  assert.equal((await f.save(owner, migrateV1(normalizeSite(example)))).status, 200);
  const browser = await chromium.launch(process.env.NIMBLE_BROWSER_CHANNEL ? { channel: process.env.NIMBLE_BROWSER_CHANNEL } : {});
  t.after(() => browser.close());
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.route('**/*', route => route.request().url().startsWith(f.base) || route.request().url().startsWith('about:') ? route.continue() : route.abort());
  const errors = [];
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(f.base + '/login.html');
  await page.locator('#email').fill(ownerCredentials.email); await page.locator('#password').fill(ownerCredentials.password);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.waitForURL('**/editor.html');
  const canvas = page.frameLocator('#canvasFrame');
  await canvas.locator('#intro').waitFor();
  const doc = () => page.evaluate(() => window.nimbleEditor.doc);
  const selected = () => page.evaluate(() => window.nimbleEditor.selected);
  const selectLayer = async id => { await page.locator('.rail-button[data-tool=layers]').click(); await page.locator('.layer-row[data-id="' + id + '"]').click(); };
  const add = async kind => { await page.locator('.rail-button[data-tool=add]').click(); await page.locator('#addPanel [data-add="' + kind + '"]').click(); return selected(); };
  const content = () => page.locator('#inspector [role=tab]', { hasText: 'Content' }).click();
  const pages = page.locator('#pagesPanel');
  let embedId;

  await t.test('customise the site menu: links, drop-downs and labels', async () => {
    await page.locator('.rail-button[data-tool=pages]').click();
    await pages.locator('[data-menu-customize]').click();
    let state = await doc();
    assert.deepEqual(state.menu.map(item => item.link.page), state.pages.map(item => item.id));
    await pages.locator('.menu-link-form input[name=label]').fill('Docs');
    await pages.locator('.menu-link-form input[name=href]').fill('https://example.com/docs');
    await pages.locator('.menu-link-form button').click();
    await pages.locator('[data-menu-path="2"] [data-menu-indent]').click();
    await pages.locator('[data-menu-path="1"] [data-menu-label]').fill('Company');
    await pages.locator('[data-menu-path="1"] [data-menu-label]').press('Enter');
    state = await doc();
    assert.equal(state.menu.length, 2);
    assert.equal(state.menu[1].label, 'Company');
    assert.deepEqual(state.menu[1].children.map(item => [item.label, item.link.href]), [['Docs', 'https://example.com/docs']]);
    const menu = canvas.locator('#site__menu');
    assert.equal(await menu.locator('.menu-sub > a').textContent(), 'Company');
    assert.equal(await menu.locator('.submenu a').getAttribute('href'), 'https://example.com/docs');
    await pages.locator('form.add-page input[name=name]').fill('Services');
    await pages.locator('form.add-page button').click();
    state = await doc();
    assert.equal(state.menu.at(-1).link.page, 'services', 'new pages join a customised menu');
    await page.locator('#pageSelect').selectOption('home');
  });

  await t.test('hamburger menu on mobile, header behaviour and anchor menu', async () => {
    await selectLayer('site__header');
    await canvas.locator('#site__menu').click();
    assert.equal(await selected(), 'site__menu');
    await page.locator('#devices button', { hasText: 'Mobile' }).click();
    await page.locator('#inspector [role=tab]', { hasText: 'Design' }).click();
    await page.locator('#inspector .field[data-key=menuMode] select').selectOption('hamburger');
    assert.equal((await doc()).nodes.site__menu.style.mobile.menuMode, 'hamburger');
    assert.equal(await canvas.locator('#site__menu > .menu-toggle').isVisible(), true);
    assert.equal(await canvas.locator('#site__menu > a').first().isVisible(), false);
    await page.locator('#devices button', { hasText: 'Desktop' }).click();
    assert.equal(await canvas.locator('#site__menu > .menu-toggle').isVisible(), false);
    assert.equal(await page.locator('#inspector .field[data-key=menuMode]').count(), 1);
    await selectLayer('site__header');
    await content();
    assert.equal(await page.locator('#inspector .field[data-key=popup]').count(), 0, 'no popup options on the header');
    await page.locator('#inspector .field[data-key=headerMode] select').selectOption('sticky');
    await page.locator('#inspector .field[data-key=scrollStyle] select').selectOption('shadow');
    assert.match(await canvas.locator('#site__header').getAttribute('class'), /hdr-sticky/);
    await selectLayer('intro');
    await content();
    assert.equal(await page.locator('#inspector .field[data-key=headerMode]').count(), 0, 'header options only on the header');
    await page.locator('#inspector [role=tab]', { hasText: 'Settings' }).click();
    await page.locator('#inspector [data-setting=name] input').fill('Welcome');
    await page.locator('#inspector [data-setting=name] input').press('Enter');
    await selectLayer('cta');
    const anchors = await add('menu-anchors');
    assert.equal(await canvas.locator('#' + anchors + ' a[href="#intro"]').textContent(), 'Welcome');
  });

  await t.test('social links', async () => {
    const id = await add('social');
    await content();
    await page.locator('#inspector [data-social-add]').click();
    await page.locator('#inspector [data-social="2"] [data-social-url]').fill('https://example.com/nimble');
    await page.locator('#inspector [data-social="2"] [data-social-url]').press('Enter');
    await page.locator('#inspector [data-social="2"] [data-social-icon]').selectOption('camera');
    await page.locator('#inspector [data-social="2"] [data-social-label]').fill('Photos');
    await page.locator('#inspector [data-social="2"] [data-social-label]').press('Enter');
    const items = (await doc()).nodes[id].props.items;
    assert.deepEqual(items[2], { label: 'Photos', url: 'https://example.com/nimble', icon: 'camera' });
    assert.equal(await canvas.locator('#' + id + ' a').count(), 3);
    await page.locator('#inspector [data-social="0"] [data-social-remove]').click();
    assert.equal((await doc()).nodes[id].props.items.length, 2);
  });

  await t.test('HTML and map embeds', async () => {
    embedId = await add('embed-html');
    await content();
    assert.equal(await page.locator('#inspector .field[data-key=address]').count(), 0, 'only HTML fields');
    await page.locator('#inspector .field[data-key=html] textarea').fill('<p id="hello">Hello from the widget</p><script>document.body.dataset.ran = "yes"</script>');
    await page.waitForFunction(id => !!window.nimbleEditor.doc.nodes[id].props.html, embedId);
    const frame = canvas.frameLocator('#' + embedId + ' iframe');
    assert.equal(await frame.locator('#hello').textContent(), 'Hello from the widget', 'static preview on the canvas');
    assert.equal(await frame.locator('body').getAttribute('data-ran'), null, 'scripts do not run in the editor');
    const map = await add('embed-map');
    await content();
    await page.locator('#inspector .field[data-key=address] textarea').fill('Karl Johans gate 1, Oslo');
    await page.waitForFunction(id => window.nimbleEditor.doc.nodes[id].props.address === 'Karl Johans gate 1, Oslo', map);
    assert.match(await canvas.locator('#' + map + ' iframe').getAttribute('src'), /^https:\/\/www\.google\.com\/maps\?q=Karl%20Johans%20gate%201%2C%20Oslo&z=14&output=embed$/);
  });

  await t.test('published menus, header and embeds work', async () => {
    await page.locator('#saveState').filter({ hasText: 'All changes saved' }).waitFor();
    const revision = (await f.request('/api/site', { auth: owner })).data.revision;
    assert.equal((await f.request('/api/publish', { method: 'POST', auth: owner, body: { revision } })).status, 200);
    const site = await context.newPage();
    site.on('pageerror', error => errors.push(error.message));
    await site.goto(f.base + '/');
    await site.locator('#site__menu .menu-sub').hover();
    assert.equal(await site.locator('#site__menu .submenu').isVisible(), true, 'drop-down on hover');
    const frame = site.frameLocator('#' + embedId + ' iframe');
    assert.equal(await frame.locator('#hello').textContent(), 'Hello from the widget');
    assert.equal(await frame.locator('body').getAttribute('data-ran'), 'yes', 'scripts run in the sandboxed frame');
    assert.equal(await site.evaluate(() => { try { return !!document.querySelector('iframe[src^="/embed/"]').contentDocument; } catch { return false; } }), false, 'the embed cannot reach the page');
    await site.evaluate(() => scrollTo(0, 400));
    await site.waitForFunction(() => document.getElementById('site__header').classList.contains('is-scrolled'));
    await site.setViewportSize({ width: 390, height: 800 });
    const toggle = site.locator('#site__menu > .menu-toggle');
    assert.equal(await toggle.isVisible(), true);
    await toggle.click();
    assert.match(await site.locator('#site__menu').getAttribute('class'), /is-open/);
    assert.equal(await site.locator('#site__menu .submenu a').isVisible(), true, 'drop-down links are listed in the open menu');
    await site.keyboard.press('Escape');
    assert.doesNotMatch(await site.locator('#site__menu').getAttribute('class'), /is-open/);
    await site.close();
  });
  assert.deepEqual(errors, []);
});
